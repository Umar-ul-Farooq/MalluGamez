/**
 * Controlled normalization for answer validation:
 * - Case-insensitive
 * - Trims leading/trailing whitespace
 * - Collapses repeated spaces
 * - Strips common punctuation
 * - Preserves Malayalam Unicode characters
 */
export function normalizeAnswer(raw: string): string {
  return raw
    .toLowerCase()
    .replace(/[.,!?;:'"`~_\-()[\]{}/\\]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Strictly validates a submitted guess against the question's configured
 * answer and explicit acceptedAnswers list (no unrestricted fuzzy matching).
 */
export function validateFastestFingerAnswer(
  rawGuess: string,
  item: FastestFingerQuestionItem
): boolean {
  const normalizedGuess = normalizeAnswer(rawGuess);
  if (!normalizedGuess) return false;

  const validNormalized = [item.answer, ...item.acceptedAnswers]
    .map(normalizeAnswer)
    .filter(Boolean);

  return validNormalized.includes(normalizedGuess);
}
