/**
 * Returns a random list of unique objects for the round,
 * excluding recently used IDs until the pool is exhausted.
 */
export function getRandomObjects(
  count: 6 | 9 | 12 | 15,
  language: 'english' | 'malayalam' = 'english',
  usedIds?: Set<string>
): Array<{ id: string; index: number; name: string; englishName: string; malayalamName: string }> {
  let pool = usedIds
    ? DRAW_IDENTIFY_WORDS.filter(w => !usedIds.has(w.id))
    : [...DRAW_IDENTIFY_WORDS];

  let selected: DrawIdentifyWord[] = [];
  if (pool.length >= count) {
    selected = [...pool].sort(() => Math.random() - 0.5).slice(0, count);
  } else {
    // Take remaining unused items first, then reset pool and fill remainder without immediate repeats
    const firstPart = [...pool].sort(() => Math.random() - 0.5);
    const firstIds = new Set(firstPart.map(i => i.id));
    if (usedIds) usedIds.clear();
    const restPool = DRAW_IDENTIFY_WORDS.filter(w => !firstIds.has(w.id)).sort(() => Math.random() - 0.5);
    selected = [...firstPart, ...restPool.slice(0, count - firstPart.length)];
  }

  if (usedIds) {
    for (const item of selected) {
      usedIds.add(item.id);
    }
  }

  return selected.map((item, index) => ({
    id: item.id,
    index,
    name: language === 'malayalam' ? `${item.malayalam} (${item.english})` : item.english,
    englishName: item.english,
    malayalamName: `${item.malayalam} (${item.manglish})`,
  }));
}
